"""Trim a pinned GitHub SDL to types and fields in our emitted SDL.

Usage: pin-schema.py full-github.graphql implemented.graphql output.graphql [schema-supplement.json]
The input reference is independent of the implementation, including nullability,
argument defaults and enum values. Never derive the reference from our types.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

source, actual, output = map(Path, sys.argv[1:4])
raw = source.read_text()


def definitions(text):
    text = re.sub(r'""".*?"""', '', text, flags=re.S)
    text = re.sub(r'^\s*#[^\n]*', '', text, flags=re.M)
    return {m[2]: (m[1], m[3] or m[4] or '') for m in re.finditer(
        r'^(type|interface|input|enum|union|scalar) (\w+)[^\n{=]*(?:\{(.*?)^\}|=([^\n]+)|$)', text, re.M | re.S)}


def fields(body):
    result = {}
    matches = list(re.finditer(r'^\t?(?:  )?(\w+)\s*(?=[:(])', body, re.M))
    for i, m in enumerate(matches):
        field = body[m.start():matches[i+1].start() if i+1 < len(matches) else len(body)].strip()
        field = re.sub(r'\s+@\w+(?:\([^)]*\))?', '', field, flags=re.S)
        result[m[1]] = re.sub(r'\s+', ' ', field).strip()
    return result


reference = definitions(raw)
live_interfaces = {}
def signature(t):
    if t['kind'] == 'NON_NULL': return signature(t['ofType']) + '!'
    if t['kind'] == 'LIST': return '[' + signature(t['ofType']) + ']'
    return t['name']

if len(sys.argv) == 5:
    supplement = Path(sys.argv[4])
    for name, t in json.loads(supplement.read_text())['data'].items():
        kind = {'OBJECT':'type', 'ENUM':'enum'}[t['kind']]
        if kind == 'enum': body = '\n' + '\n'.join('  '+v['name'] for v in t['enumValues']) + '\n'
        else:
            selected = fields(reference[name][1]) if name in reference else {}
            for f in t['fields']:
                args = ', '.join(a['name'] + ': ' + signature(a['type']) + (' = '+a['defaultValue'] if a['defaultValue'] is not None else '') for a in f['args'])
                selected[f['name']] = f['name'] + ('('+args+')' if args else '') + ': ' + signature(f['type'])
            body = '\n' + '\n'.join('  '+v for v in selected.values()) + '\n'
        reference[name] = (kind, body)
        live_interfaces[name] = [v['name'] for v in t['interfaces'] or []]

implemented = definitions(actual.read_text())
lines = ['# Trimmed from octokit/graphql-schema at 82ff2d4780080e6929ebb95608cefa22dfa05ac7.',
         '# Full source SHA-256: ' + hashlib.sha256(raw.encode()).hexdigest(),
         '# Generated by scripts/oracle/pin-schema.py from independent GitHub SDL.', '']
if len(sys.argv) == 5:
    lines.insert(3, '# Live schema supplement SHA-256: ' + hashlib.sha256(supplement.read_bytes()).hexdigest())
for name, (kind, body) in sorted(implemented.items()):
    if name in ('Int', 'String', 'Boolean', 'ID', 'Float'): continue
    refkind, refbody = reference[name]
    assert kind == refkind, (name,kind,refkind)
    if kind == 'scalar': lines.append(f'scalar {name}\n'); continue
    if kind == 'union':
        members = [v.strip() for v in body.split('|')]
        assert set(members) <= set(v.strip() for v in refbody.split('|'))
        lines.append(f'union {name} = ' + ' | '.join(members) + '\n'); continue
    if kind == 'enum':
        values = re.findall(r'^  (\w+)', refbody, re.M)
        lines.append(f'enum {name} {{\n' + '\n'.join('  '+v for v in values) + '\n}\n'); continue
    rf = fields(refbody)
    selected = [rf[f] for f in fields(body)]
    if name in live_interfaces: interfaces = [v for v in live_interfaces[name] if v in implemented]
    else:
        header = re.search(r'^'+kind+' '+name+r'\b([^\n{]*)', re.sub(r'\"\"\".*?\"\"\"', '', raw, flags=re.S), re.M)[1]
        interfaces = [v for v in re.findall(r'\w+', header.partition('implements')[2]) if v in implemented]
    suffix = ' implements ' + ' & '.join(interfaces) if interfaces else ''
    lines.append(f'{kind} {name}{suffix} {{\n' + '\n'.join('  '+f for f in selected) + '\n}\n')
output.write_text('\n'.join(lines))
